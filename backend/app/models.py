"""SQLAlchemy models. Every product-scoped table carries tenant_id and product_id."""

from datetime import datetime, timezone

from sqlalchemy import Float, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from .db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Timestamped:
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(default=utcnow, onupdate=utcnow)


class Scoped(Timestamped):
    """Mixin for tenant/product-scoped rows."""

    tenant_id: Mapped[str] = mapped_column(String(64), index=True)
    product_id: Mapped[str] = mapped_column(String(64), index=True)


class Tenant(Base, Timestamped):
    __tablename__ = "tenants"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    name: Mapped[str] = mapped_column(String(200))


class Product(Base, Timestamped):
    __tablename__ = "products"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    tenant_id: Mapped[str] = mapped_column(String(64), index=True)
    name: Mapped[str] = mapped_column(String(200))
    url: Mapped[str] = mapped_column(String(500))
    description: Mapped[str] = mapped_column(Text, default="")
    status: Mapped[str] = mapped_column(String(40), default="CREATED")
    login_json: Mapped[str] = mapped_column(Text, default="")  # LoginConfig JSON or empty


class CrawlJob(Base, Scoped):
    __tablename__ = "crawl_jobs"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    type: Mapped[str] = mapped_column(String(40), default="DISCOVERY")
    status: Mapped[str] = mapped_column(String(40), default="QUEUED")  # QUEUED | RUNNING | DONE | FAILED
    stage: Mapped[str] = mapped_column(String(40), default="CREATED")
    progress: Mapped[float] = mapped_column(Float, default=0.0)
    message: Mapped[str] = mapped_column(Text, default="")
    stats_json: Mapped[str] = mapped_column(Text, default="{}")


class Page(Base, Scoped):
    __tablename__ = "pages"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    url: Mapped[str] = mapped_column(String(1000))
    path: Mapped[str] = mapped_column(String(500), index=True)
    title: Mapped[str] = mapped_column(String(300), default="")
    text: Mapped[str] = mapped_column(Text, default="")
    headings_json: Mapped[str] = mapped_column(Text, default="[]")
    elements_json: Mapped[str] = mapped_column(Text, default="[]")
    links_json: Mapped[str] = mapped_column(Text, default="[]")


class Feature(Base, Scoped):
    __tablename__ = "features"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    page_id: Mapped[str] = mapped_column(String(64), index=True)
    name: Mapped[str] = mapped_column(String(200))
    slug: Mapped[str] = mapped_column(String(200), index=True)
    kind: Mapped[str] = mapped_column(String(20), default="page")  # page | action
    description: Mapped[str] = mapped_column(Text, default="")
    route: Mapped[str] = mapped_column(String(500))
    nav_path_json: Mapped[str] = mapped_column(Text, default="[]")
    elements_json: Mapped[str] = mapped_column(Text, default="[]")
    questions_json: Mapped[str] = mapped_column(Text, default="[]")
    keywords_json: Mapped[str] = mapped_column(Text, default="[]")


class NavigationEdge(Base, Scoped):
    __tablename__ = "navigation_edges"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    from_path: Mapped[str] = mapped_column(String(500))
    to_path: Mapped[str] = mapped_column(String(500))
    selector: Mapped[str] = mapped_column(String(500), default="")
    label: Mapped[str] = mapped_column(String(200), default="")


class QnA(Base, Scoped):
    __tablename__ = "qna"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    feature_id: Mapped[str] = mapped_column(String(64), default="", index=True)
    question: Mapped[str] = mapped_column(Text)
    answer: Mapped[str] = mapped_column(Text)


class DemoFlow(Base, Scoped):
    __tablename__ = "demo_flows"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    feature_id: Mapped[str] = mapped_column(String(64), index=True)
    name: Mapped[str] = mapped_column(String(200))
    description: Mapped[str] = mapped_column(Text, default="")
    steps_json: Mapped[str] = mapped_column(Text, default="[]")


class KnowledgeChunk(Base, Scoped):
    __tablename__ = "knowledge_chunks"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    source_type: Mapped[str] = mapped_column(String(40))  # page | feature | qna
    source_id: Mapped[str] = mapped_column(String(64))
    title: Mapped[str] = mapped_column(String(300), default="")
    text: Mapped[str] = mapped_column(Text)


class ChatSession(Base, Timestamped):
    """Session ids are generated by the widget per product; the same id under another product is a different session."""

    __tablename__ = "chat_sessions"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    product_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    tenant_id: Mapped[str] = mapped_column(String(64), index=True)


class ChatMessage(Base, Scoped):
    __tablename__ = "chat_messages"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    session_id: Mapped[str] = mapped_column(String(64), index=True)
    role: Mapped[str] = mapped_column(String(20))  # user | assistant
    content: Mapped[str] = mapped_column(Text)
    meta_json: Mapped[str] = mapped_column(Text, default="{}")
    seq: Mapped[int] = mapped_column(Integer, default=0)


class DemoRun(Base, Scoped):
    __tablename__ = "demo_runs"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    session_id: Mapped[str] = mapped_column(String(64), index=True)
    title: Mapped[str] = mapped_column(String(200))
    steps_json: Mapped[str] = mapped_column(Text, default="[]")
    current_step: Mapped[int] = mapped_column(Integer, default=0)
    status: Mapped[str] = mapped_column(String(20), default="RUNNING")  # RUNNING | DONE | FAILED | STOPPED
    error: Mapped[str] = mapped_column(Text, default="")
